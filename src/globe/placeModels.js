export const MODEL_TYPES = Object.keys(MODEL_LABEL)

/** The kind's model when the server sent no model_type (an older server). */
export const KIND_DEFAULT = {
    refinery: "refinery", fuel_depot: "fuel_depot", fuel_station: "fuel_station", roundabout: "roundabout",
    gathering: "rally", assembly: "rally", action: "rally", strike: "city",
    arms_company: "factory", lobby_office: "office_building", listed_site: "generic_building",
}

/** Bumped whenever the models are regenerated (see aircraftModels.js). */
export const MODEL_VERSION = 2

/** One revolution in this many seconds (owner: "slowly rotating"). */
export const TURN_SECONDS = 20

/** The model type of a place: the server's, else its kind's, else a building. */
export function modelTypeOf(p) {
    const t = p?.model_type
    if (t && MODEL_LABEL[t]) return t
    return KIND_DEFAULT[p?.kind] || KIND_DEFAULT[p?.place_kind] || "generic_building"
}

export function modelLabelOf(p) {
    return p?.model_label || MODEL_LABEL[modelTypeOf(p)]
}

/** The file of a model type (an unknown type is a generic building). */
export function modelUrl(type) {
    const t = MODEL_LABEL[type] ? type : "generic_building"
    return `/models/place/${t}.glb?v=${MODEL_VERSION}`
}
